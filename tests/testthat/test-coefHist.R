test_that("coefHist builds correct coefHist objects (1)", {
  x1<-rnorm(20, mean = 0, sd = 1)
  x2<-rnorm(20, mean = 0, sd = 2)
  x3<-rnorm(20, mean = 0, sd = 3)
  x4<-rnorm(20, mean = 0, sd = 1)
  x5<-rnorm(20, mean = 0, sd = 2)
  x6<-rnorm(20, mean = 0, sd = 4)
  x7<-rnorm(20, mean = 0, sd = 3)
  x8<-rnorm(20, mean = 0, sd = 2)
  x9<-rnorm(20, mean = 0, sd = 1)
  x10<-rnorm(20, mean = 0, sd = 4)
  x11<-rnorm(20, mean = 0, sd = 4)
  x12<-rnorm(20, mean = 0, sd = 4)
  x13<-rnorm(20, mean = 0, sd = 4)
  x14<-rnorm(20, mean = 0, sd = 4)
  x15<-rnorm(20, mean = 0, sd = 4)
  e<-rnorm(20, mean = 0, sd = 0.5)
  y<-2+x1+(2*x2)+(3*x3)+(0.5*x4)-x5+e
  data<-cbind(y,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15)
  colnames(data)<-c("y","x1","x2","x3","x4","x5","x6","x7","x8","x9","x10","x11","x12","x13","x14","x15")
  M<-5
  mSpace<-modelSpace(data,M)
  Post<-Posterior(mSpace)
  histPlots<-coefHist(Post,BW="FD",binW=NULL)
  for (i in 1:15){expect_equal(class(histPlots[[i]]),c("gg", "ggplot"))}
})

